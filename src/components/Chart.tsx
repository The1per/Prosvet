import { BASELINE, type Week } from "../data/series";
import { EVENT_BY_DATE } from "../data/events";
import { T, fmtWeek, type Lang } from "../i18n";
import { moodColor } from "../mood";

/**
 * Кривая тревоги.
 *
 * ШКАЛА. Ось не 0…100. Опрос за всё время ходил в пределах 32…70 %, и
 * растянуть ось на всю сотню значило бы сплющить весь ряд в узкую полосу
 * посередине и спрятать разницу между спокойной неделей и мобилизацией.
 *
 * ЛИНИИ ПОСЕТИТЕЛЯ ЗДЕСЬ НЕТ, И ЭТО НАРОЧНО: ответ посетителя относится к
 * текущей неделе, а кривая -- к прошедшим. Пересекать их на одном полотне
 * значит сравнивать разные недели.
 */

const W_БАЗА = 1000;

/**
 * ВЫСОТА ХОЛСТА СЧИТАЕТСЯ ПО КОРОБКЕ, А НЕ ЗАДАНА ЧИСЛОМ.
 *
 * Здесь стояло H = 430 при W = 1000, то есть холст с намертво заданными
 * пропорциями 2.33:1. Коробка же под график шире и ниже -- её высоту задаёт
 * раскладка, чтобы левая карточка кончалась вровень с опросом. Браузер
 * вписывал холст в коробку целиком и центрировал, и разница уходила в пустые
 * полосы сверху и снизу. Измерено: на экране 1600 -- по 93 пикселя с каждой
 * стороны, на 1920 -- по 58. Именно эта полоса и отодвигала ряд важных дат от
 * строки поиска, и именно она съедала высоту у самой кривой.
 *
 * Теперь высота холста берётся из пропорций коробки, полос нет вовсе, и вся
 * высота достаётся кривой. Пределы -- на случай очень узкой или очень широкой
 * коробки, где деление вырождается.
 */
const H_МИН = 300;
const H_МАКС = 900;
const H_ПО_УМОЛЧАНИЮ = 430; // до первого измерения

/**
 * ЕДИНИЦА ХОЛСТА. На большом экране холст условный: W = 1000 при коробке
 * шириной 1450, то есть всё нарисованное увеличивается в полтора раза, и
 * кегль 16 читается как 23. На телефоне та же условность работает против:
 * коробка 390 пикселей, множитель 0.39, и кегль 16 превращается в 6 --
 * прочесть нельзя. Поэтому на телефоне холст мерится В ПИКСЕЛЯХ: W равно
 * ширине коробки, и все размеры здесь -- настоящие.
 */

// PAD.t держит ряд подписей и табличку недели. 96 -- ровно столько, сколько им
// нужно: рамка кончается на 35, табличка занимает 44 начиная с PAD.t - 52.
// На телефоне таблички нет, зато подписи стоят в три ряда -- им нужно больше.
// ВЕРХНЕЕ ПОЛЕ БЫЛО 96. Столько держали подписи событий вместе с полочками,
// которые тянутся от них к кривой. Метки стояли высоко, полочки выходили
// длинными, и между заголовком карточки и самой кривой зияла полоса воздуха.
// 74 хватает и подписям, и полочкам, а кривой достаётся двадцать два пикселя.
const PAD_БАЗА = { l: 34, r: 12, t: 74, b: 30 };
// Слева ровно столько, сколько нужно двузначному числу мелким кеглем;
// справа -- почти ничего: кривая должна доходить до края.
const PAD_ТЕЛ = { l: 18, r: 2, b: 24 };
const LABEL_Y = 22; // верхний ряд подписей
const ШАГ_РЯДА = 36; // между рядами подписей на телефоне (рамка -- 26)
const PADX_ТЕЛ = 10; // поля внутри рамки на телефоне -- уже, чем на экране
const КЕГЛЬ_ТЕЛ = 12; // и кегль там меньше: рамки уже, промежутки шире
// Средняя ширина знака -- примерно 0.58 кегля для этого шрифта. Считаем
// ширину рамки под текст, а если текст в свою долю не влезает -- УМЕНЬШАЕМ
// КЕГЛЬ, а не режем рамку: обрезанная рамка и была причиной того, что буквы
// на неё находили.
const ШИР_ЗНАКА = 0.58;
const PADX = 22; // поля внутри рамки
const КЕГЛЬ = 15; // желаемый; уменьшается только если иначе не влезть
const КЕГЛЬ_МИН = 11;
const КЕГЛЬ_ТЕЛ_МИН = 12;  // минимальный кегль на странице -- 12, см. ПОЛ

const LO = 26;
const HI = 76;
const TICKS = [30, 40, 50, 60, 70];

/**
 * ЦВЕТ КРИВОЙ ПОСТОЯНЕН. Раньше вся линия перекрашивалась в цвет выбранной
 * недели: вся история меняла цвет от того, куда ткнули мышью, и в
 * спокойных неделях кривая уходила в тусклую бирюзу. Здесь она -- ось отсчёта,
 * а не показание, и цвет у неё один, видный на обеих темах.
 */
const CURVE = "var(--curve)";

type Props = {
  data: Week[];
  lang: Lang;
  sel: number;
  onSel: (i: number) => void;
  showFom: boolean;
  /**
   * Простой вид: БЕЛОЕ свечение кривой выключено. Цветного свечения важных
   * дат это не касается -- оно не украшение, а способ отличить событие от
   * обычной недели.
   */
  простой?: boolean;
  /** Показывать ли саму кривую индекса. Выключают, чтобы смотреть один опрос. */
  индекс?: boolean;
  phone?: boolean;
  /**
   * Что поставить в правый верхний угол ПОЛЯ КРИВОЙ (не полотна). Снаружи
   * это место не вычислить: верхнее поле меняется от числа рядов подписей,
   * а те -- от ширины экрана.
   */
  уголок?: React.ReactNode;
};

export default function Chart({ data, lang, sel, onSel, showFom, простой = false, индекс = true, phone = false, уголок }: Props) {
  const ref = useRef<SVGSVGElement>(null);
  const [hovering, setHovering] = useState(false);
  /**
   * ВЕДЁМ ЛИ НЕДЕЛЮ ПАЛЬЦЕМ.
   *
   * На телефоне у пальца два дела на одном месте: листать страницу и выбирать
   * неделю. Раньше побеждало то одно, то другое -- сперва полотно забирало
   * все касания и страница не листалась, потом листание забрало всё и неделю
   * стало не сдвинуть. Развели их по началу жеста: палец, опущенный НА САМ
   * КРУЖОК выбранной недели, ведёт неделю; опущенный где угодно ещё -- листает.
   * Короткое касание мимо кружка по-прежнему просто выбирает неделю.
   */
  // Признак живёт в ref, а не только в state: между нажатием и первым
  // движением React может не успеть перерисовать, и обработчик движения читал
  // бы старое значение -- ведение не начиналось бы вовсе. State нужен лишь
  // для touch-action, которому нужна перерисовка.
  const тащимRef = useRef(false);
  const [тащим, setТащим] = useState(false);
  const начало = useRef<{ x: number; y: number } | null>(null);
  const вести = (да: boolean) => {
    тащимRef.current = да;
    setТащим(да);
  };

  // Коробка меряется, а не угадывается: её размер задаёт раскладка.
  const [бокс, setБокс] = useState<{ w: number; h: number } | null>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const o = new ResizeObserver(([e]) => {
      const { width, height } = e.contentRect;
      if (width && height) setБокс({ w: width, h: height });
    });
    o.observe(el);
    return () => o.disconnect();
  }, []);

  // На телефоне единица холста -- пиксель; на большом экране холст условный.
  const W = phone && бокс ? Math.round(бокс.w) : W_БАЗА;

  /**
   * СКОЛЬКО РЯДОВ ПОДПИСЕЙ. Считается по самой длинной из них, а не назначено:
   * на 390 пикселях в ряд встают три, на 320 -- только две, и назначенная
   * тройка там накладывала рамки друг на друга. Сколько влезает столбцов --
   * столько и берём, остальное уходит в ряды.
   */
  const рядов = useMemo(() => {
    if (!phone) return 1;
    const n = data.filter((d) => EVENT_BY_DATE[d.date]).length;
    if (!n) return 1;
    const длина = Math.max(
      ...data.filter((d) => EVENT_BY_DATE[d.date]).map((d) => {
        const ev = EVENT_BY_DATE[d.date];
        // +3 на приписанный год: столбцы считаются по той же длине, что
        // потом рисуется, иначе рамки не помещаются и наезжают.
        return (lang === "ru" ? ev.shortRu : ev.shortEn).length + 3;
      }),
    );
    // На телефоне подписи можно сжать до 10: «COVID, 2-я волна» при 11
    // требовала столько места, что рядов становилось четыре, и они съедали
    // высоту у самой кривой.
    const нужно = длина * КЕГЛЬ_ТЕЛ_МИН * ШИР_ЗНАКА + PADX_ТЕЛ;
    const столбцов = Math.max(1, Math.floor((W - PAD_ТЕЛ.l - PAD_ТЕЛ.r) / нужно));
    return Math.ceil(n / столбцов);
  }, [phone, data, lang, W]);

  /**
   * ГОДЫ НА ОСИ. Все до одного и В ОДИН РЯД: пропущенный год читается как
   * отсутствующий отрезок времени, а два ряда превращают ось в лесенку.
   *
   * Полностью пишутся только КРАЙНИЕ -- они говорят, где ряд начинается и где
   * кончается. Остальные сокращены до «’21»: между ними и так понятно, что
   * идут годы подряд, а короткая подпись втрое экономнее.
   *
   * Ряд начинается в июле 2019-го, поэтому первый промежуток вдвое короче
   * остальных. Чтобы «2019» не налезал на «’20», крайние подписи выходят за
   * поле оси -- влево и вправо, в отступы полотна, где всё равно пусто.
   */
  const годы = useMemo(() => {
    const т: { year: number; x: number }[] = [];
    const шир = W - (phone ? PAD_ТЕЛ.l + PAD_ТЕЛ.r : PAD_БАЗА.l + PAD_БАЗА.r);
    const л = phone ? PAD_ТЕЛ.l : PAD_БАЗА.l;
    data.forEach((d, i) => {
      const yr = +d.date.slice(0, 4);
      if (!т.some((v) => v.year === yr)) т.push({ year: yr, x: л + (i / (data.length - 1)) * шир });
    });
    // Самый узкий промежуток МЕЖДУ СРЕДНИМИ подписями: крайние стоят с краю,
    // их ширина упирается не в соседа, а в поле полотна.
    let мин = Infinity;
    for (let i = 1; i + 2 < т.length; i++) мин = Math.min(мин, т[i + 1].x - т[i].x);
    if (!isFinite(мин)) мин = шир;
    const ПОЛ = 12;   // минимальный кегль на странице; ниже не опускаемся нигде
    const потолок = phone ? 13 : 16;
    // Средняя подпись -- три знака («’21»), крайняя -- четыре.
    const кегль = Math.max(ПОЛ, Math.min(потолок, (мин - 4) / (3 * ШИР_ЗНАКА)));
    return { точки: т, кегль };
  }, [data, phone, W]);

  // Верхнее поле держит ровно столько рядов подписей, сколько получилось;
  // нижнее -- один ряд годов или два.
  const PAD = useMemo(
    () =>
      phone
        ? {
            ...PAD_ТЕЛ,
            // ПОДПИСЕЙ СОБЫТИЙ НА ТЕЛЕФОНЕ БОЛЬШЕ НЕТ -- они переехали в
            // отдельную полосу над графиком (см. App). Четыре ряда рамок
            // держали сто пятьдесят семь пикселей верхнего поля: почти
            // половину высоты, отданной кривой. Осталась только шапка под
            // выбранную точку.
            t: 26,
            b: PAD_ТЕЛ.b,
          }
        : PAD_БАЗА,
    [phone, рядов, годы],
  );
  const H = бокс
    ? phone
      ? Math.round(бокс.h)
      : Math.round(Math.min(H_МАКС, Math.max(H_МИН, (W * бокс.h) / бокс.w)))
    : H_ПО_УМОЛЧАНИЮ;

  const x = useCallback(
    (i: number) => PAD.l + (i / (data.length - 1)) * (W - PAD.l - PAD.r),
    [data.length, W, PAD],
  );
  const y = useCallback(
    (v: number) => PAD.t + (1 - (v - LO) / (HI - LO)) * (H - PAD.t - PAD.b),
    [H, PAD],
  );

  const { line, area, fomLine, markers, полосы, gaps } = useMemo(() => {
    const pts = data.map((d, i) => [x(i), y(d.idx)] as const);
    let p = `M${pts[0][0].toFixed(2)},${pts[0][1].toFixed(2)}`;
    for (let i = 0; i < pts.length - 1; i++) {
      const p0 = pts[i - 1] ?? pts[i];
      const p1 = pts[i];
      const p2 = pts[i + 1];
      const p3 = pts[i + 2] ?? p2;
      const c1x = p1[0] + (p2[0] - p0[0]) / 6;
      const c1y = p1[1] + (p2[1] - p0[1]) / 6;
      const c2x = p2[0] - (p3[0] - p1[0]) / 6;
      const c2y = p2[1] - (p3[1] - p1[1]) / 6;
      p += `C${c1x.toFixed(2)},${c1y.toFixed(2)} ${c2x.toFixed(2)},${c2y.toFixed(2)} ${p2[0].toFixed(2)},${p2[1].toFixed(2)}`;
    }
    const last = pts[pts.length - 1];
    const a = `${p}L${last[0].toFixed(2)},${H - PAD.b}L${pts[0][0].toFixed(2)},${H - PAD.b}Z`;

    /**
     * КУСОК ТОЙ ЖЕ КРИВОЙ с недели `от` по неделю `до`.
     *
     * Изгибы считаются той же формулой и по тем же соседям, что и вся линия, --
     * иначе окрашенный кусок лёг бы РЯДОМ с серебряной кривой, а не на неё.
     * Соседи берутся и за пределами куска: изгиб на его краю задаётся неделей
     * снаружи, и без неё кусок отходил бы от линии на стыке.
     */
    const кусок = (от: number, до: number) => {
      let d = `M${pts[от][0].toFixed(2)},${pts[от][1].toFixed(2)}`;
      for (let i = от; i < до; i++) {
        const p0 = pts[i - 1] ?? pts[i];
        const p1 = pts[i];
        const p2 = pts[i + 1];
        const p3 = pts[i + 2] ?? p2;
        const c1x = p1[0] + (p2[0] - p0[0]) / 6;
        const c1y = p1[1] + (p2[1] - p0[1]) / 6;
        const c2x = p2[0] - (p3[0] - p1[0]) / 6;
        const c2y = p2[1] - (p3[1] - p1[1]) / 6;
        d += `C${c1x.toFixed(2)},${c1y.toFixed(2)} ${c2x.toFixed(2)},${c2y.toFixed(2)} ${p2[0].toFixed(2)},${p2[1].toFixed(2)}`;
      }
      return d;
    };

    // Опрос рисуется отрезками: там, где волн не было, линию тянуть нельзя --
    // получится измерение, которого не делали.
    let f = "";
    let open = false;
    data.forEach((d, i) => {
      if (d.fom == null) {
        open = false;
        return;
      }
      f += `${open ? "L" : "M"}${x(i).toFixed(1)},${y(d.fom).toFixed(1)}`;
      open = true;
    });

    // РАСХОЖДЕНИЕ. Полоска от прибора до опроса на каждой неделе, где волна
    // была. Цвет говорит, кто выше. Тянуть сплошную заливку нельзя: между
    // волнами опроса нет, и залитый промежуток был бы измерением, которого не
    // делали. Лента строится ПАРАМИ соседних недель: четырёхугольник между
    // прибором и опросом. Тонкая лента -- согласие, толстая -- расхождение.
    //
    // РИСУЕТСЯ, ТОЛЬКО ЕСЛИ ВИДНЫ ОБЕ КРИВЫЕ. Разница между прибором и опросом
    // при выключенной кривой прибора -- это заливка до линии, которой на
    // картинке нет: читателю показывают край чего-то невидимого.
    const gaps: { d: string; up: boolean }[] = [];
    for (let i = 0; i + 1 < data.length; i++) {
      const A = data[i];
      const B = data[i + 1];
      if (A.fom == null || B.fom == null) continue;
      const x1 = x(i);
      const x2 = x(i + 1);
      gaps.push({
        d: `M${x1.toFixed(1)},${y(A.idx).toFixed(1)}L${x2.toFixed(1)},${y(B.idx).toFixed(1)}L${x2.toFixed(1)},${y(B.fom).toFixed(1)}L${x1.toFixed(1)},${y(A.fom).toFixed(1)}Z`,
        up: A.fom + B.fom > A.idx + B.idx,
      });
    }

    // ОДИН РЯД. Подписи стоят ровной строкой наверху, в порядке дат, каждой
    // отведена равная доля ширины -- а к своей точке на кривой от неё идёт
    // выноска. Раскладка по нескольким рядам читалась как лесенка; ровная
    // строка читается как оглавление.
    const сырые = data
      .map((d, i) => ({ d, i }))
      // Только разобранные недели. Подписи из самих данных давали лишние
      // метки -- в том числе вторую «мобилизацию» на неделе после неё.
      .filter((o) => EVENT_BY_DATE[o.d.date]);
    // НА ТЕЛЕФОНЕ РЯДОВ ТРИ. Девять подписей в одну строку по 390 пикселей --
    // это 43 пикселя на подпись, куда «Мобилизация» не влезает ни при каком
    // кегле. Три ряда дают втрое больше места каждой; лесенка на телефоне
    // читается нормально, потому что глаз и так идёт сверху вниз.
    /**
     * ПОДПИСИ РАСТЯНУТЫ ПО ВСЕЙ ШИРИНЕ, а не сжаты к середине. Прежде каждой
     * отводилась равная доля, и подпись стояла в СЕРЕДИНЕ своей доли: крайние
     * отступали от краёв на полдоли, и весь ряд читался сбитым к центру.
     * Теперь середины подписей идут ОТ КРАЯ ДО КРАЯ, а к самим краям их не
     * пускает зажим по половине собственной ширины.
     * Справа оставлено место под кнопку поиска -- она сидит в углу графика.
     */
    // Место под лупу здесь больше не резервируется: она уехала ВНИЗ, в угол
    // поля кривой, и с рядом подписей уже не встречается.
    const лев = 2;
    const прав = W - 2;
    const столбцов = Math.ceil(сырые.length / рядов);
    const шаг = (прав - лев) / столбцов;
    // Сперва размеры всех подписей, потом расстановка: раскладывать их можно
    // только зная САМУЮ ШИРОКУЮ -- от неё зависит, где встанут крайние.
    const мерки = сырые.map((o, k) => {
      const ev = EVENT_BY_DATE[o.d.date];
      // На телефоне выносок нет, и метка сама говорит, куда показывает:
      // к ней приписан год недели. Двух знаков хватает -- ряд короче века.
      const имя = lang === "ru" ? ev.shortRu : ev.shortEn;
      const text = phone ? имя + " ’" + o.d.date.slice(2, 4) : имя;
      const поля = phone ? PADX_ТЕЛ : PADX;
      const место = шаг - (phone ? 5 : 8);
      const кегль = Math.max(
        phone ? КЕГЛЬ_ТЕЛ_МИН : КЕГЛЬ_МИН,
        Math.min(phone ? КЕГЛЬ_ТЕЛ : КЕГЛЬ, (место - поля) / (text.length * ШИР_ЗНАКА)),
      );
      return {
        o,
        k,
        text,
        кегль,
        wid: text.length * кегль * ШИР_ЗНАКА + поля,
        ряд: 0,
        столбец: 0,
      };
    });
    // СТОЛБЦЫ РАВНОЙ ВЫСОТЫ. Прежде подписи резались по рядов штук подряд, и
    // при семи метках на три столбца выходило 3+3+1 -- последний столбец
    // стоял одинокой меткой, а первые два кучей. Теперь остаток
    // раскладывается по первым столбцам: 3+2+2.
    if (phone) {
      const базовый = Math.floor(мерки.length / столбцов);
      const остаток = мерки.length % столбцов;
      let i = 0;
      for (let с = 0; с < столбцов; с++) {
        const сколько = базовый + (с < остаток ? 1 : 0);
        for (let р = 0; р < сколько; р++, i++) {
          мерки[i].столбец = с;
          мерки[i].ряд = р;
        }
      }
    } else {
      мерки.forEach((m, k) => (m.столбец = k));
    }
    // Крайние подписи отступают от края на ПОЛОВИНУ САМОЙ ШИРОКОЙ, и уже
    // между этими двумя точками всё раскладывается поровну. Так ряд занимает
    // всю ширину, ни одна подпись не вылезает за полотно и расстояние между
    // соседями одинаково -- прежний зажим по краю сдвигал только крайнюю и
    // она наезжала на следующую.
    /**
     * ПОЛОСА СОБЫТИЯ. Метка стоит на одной неделе, а событие длится месяцами:
     * Курское вторжение держало индекс высоко четырнадцать недель, вторжение
     * тринадцать, вторая волна ковида пятнадцать. Точка на пике врала о
     * длительности -- полоса не врёт.
     *
     * Граница полосы -- правило, а не глазомер: тянем от помеченной недели в
     * обе стороны, пока показание держится не ниже СЕРЕДИНЫ между пиком
     * события и обычной неделей. Соседняя ниже середины -- полоса кончилась.
     * У «Крокуса» и мятежа так выходит одна неделя, и это верно: они были
     * резкими и короткими.
     *
     * ПОКАЗЫВАЕТСЯ ЦВЕТОМ САМОЙ ЛИНИИ, а не заливкой позади неё. Заливка --
     * прямоугольник во всю высоту поля -- закрашивала и те значения, которых
     * в эти недели не было, и читалась как отдельный слой поверх картинки.
     * Перекрашенный кусок кривой говорит ровно то, что измерено: вот эти
     * недели, вот на какой они высоте.
     */
    const полосы = сырые.map((o) => {
      const пик = o.d.idx;
      const порог = (пик + BASELINE) / 2;
      let a = o.i;
      let b = o.i;
      while (a > 0 && data[a - 1].idx >= порог) a--;
      while (b < data.length - 1 && data[b + 1].idx >= порог) b++;
      // Событие одной недели -- не пустой путь, а точка: круглый наконечник
      // рисует её сам, и «Крокус» остаётся видимым, не удлиняясь враньём.
      return { i: o.i, d: кусок(a, b), недель: b - a + 1, цвет: moodColor(пик, 6) };
    });

    const макс = Math.max(...мерки.map((m) => m.wid), 0);
    const лев2 = лев + макс / 2;
    const прав2 = Math.max(лев2, прав - макс / 2);
    const ms = мерки.map((m) => ({
      i: m.o.i,
      x: x(m.o.i),
      y: y(m.o.d.idx),
      text: m.text,
      кегль: m.кегль,
      ряд: m.ряд,
      ly: LABEL_Y + m.ряд * ШАГ_РЯДА,
      lx: столбцов > 1 ? лев2 + ((прав2 - лев2) * m.столбец) / (столбцов - 1) : (лев2 + прав2) / 2,
      wid: m.wid,
    }));

    return {
      line: p,
      area: a,
      fomLine: f,

      markers: ms,
      полосы,
      gaps,
    };
  }, [data, lang, x, y, W, PAD, phone, рядов]);

  /** Плечо выноски не должно оказаться ниже самой точки. */
  const low = (py: number) => Math.max(py, PAD.t - 6);

  /**
   * Курсор ведёт неделю ТОЛЬКО когда он в поле кривой. Полотно шире поля: сверху
   * на нём стоит ряд подписей, и раньше движение мыши по подписям уже
   * перематывало неделю -- прочесть подпись, не сбив выбор, было нельзя.
   */
  const вПоле = (clientY: number) => {
    const r = ref.current?.getBoundingClientRect();
    if (!r) return false;
    return ((clientY - r.top) / r.height) * H >= PAD.t - 8;
  };

  /** Палец на самом кружке выбранной недели? Радиус щедрый: по кружку в
      шесть пикселей пальцем не попасть. */
  const наКружке = (clientX: number, clientY: number) => {
    const r = ref.current?.getBoundingClientRect();
    if (!r) return false;
    const px = r.left + (cx / W) * r.width;
    const py = r.top + (cy / H) * r.height;
    return Math.hypot(clientX - px, clientY - py) <= 26;
  };

  const pick = (clientX: number, clientY: number) => {
    const r = ref.current?.getBoundingClientRect();
    if (!r || !вПоле(clientY)) return;
    const rel = ((clientX - r.left) / r.width) * W;
    const i = Math.round(((rel - PAD.l) / (W - PAD.l - PAD.r)) * (data.length - 1));
    onSel(Math.max(0, Math.min(data.length - 1, i)));
  };

  const cur = data[sel];
  const cx = x(sel);
  const cy = y(cur.idx);
  const flip = cx > W * 0.6;
  // Табличка держится на ОДНОМ уровне -- прямо под рядом подписей. Прыгая
  // вслед за точкой, она перекрывала то кривую, то подписи, и глаз каждый раз
  // искал её заново.
  const boxY = PAD.t - 52;
  const boxH = 44;

  return (
    <div className="relative flex w-full flex-1 select-none" draggable={false} onDragStart={(e) => e.preventDefault()}>
      {уголок && (
        <div
          className="absolute z-20"
          /* Отступ слева -- по левому полю ПОЛЯ КРИВОЙ, а не полотна: у самого
             края стоят подписи оси, и лупа села бы прямо на «70». */
          /* НА ТЕЛЕФОНЕ УГОЛОК СИДИТ У САМОГО ВЕРХА ПОЛОТНА, а не под верхним
             полем. Поле там всего 26 пикселей и держит шапку выбранной точки,
             но кнопки диапазона, поиска и настроек в неё не упираются -- шапка
             под ними прозрачна. Двадцать восемь пикселей, которые они забирали
             у кривой, возвращены ей.

             На экране уголок остаётся под верхним полем: там в нём стоит ряд
             подписей событий, и кнопки сели бы прямо на них. */
          /* НА ТЕЛЕФОНЕ УГОЛОК РАСТЯНУТ ВО ВСЮ ШИРИНУ ПОЛЯ. Кнопки поиска и
             настроек стояли слева, столбиком под диапазоном, и занимали два
             яруса над кривой. Теперь ярус один: диапазон слева, кнопки у
             правого края -- App раскладывает их сам, а сюда приходит готовая
             строка. */
          style={{
            left: `${(PAD.l / W) * 100}%`,
            right: phone ? `${(PAD.r / W) * 100}%` : undefined,
            top: phone ? 0 : `${(PAD.t / H) * 100}%`,
            marginLeft: 4,
            marginRight: phone ? 4 : undefined,
            marginTop: phone ? 2 : 6,
          }}
        >
          {уголок}
        </div>
      )}
      <svg
        ref={ref}
        viewBox={`0 0 ${W} ${H}`}
        className="w-full"
        /**
         * ПЕРЕТАСКИВАНИЕ ЗАПРЕЩЕНО. Нажатие на svg в браузере начинает
         * системное перетаскивание картинки: пока оно идёт, движения мыши
         * полотну не приходят, и точка замирает на графике до следующего
         * нажатия. Ровно это и происходило, если щёлкнуть, ведя курсор.
         */
        onDragStart={(e) => e.preventDefault()}
        style={{
          height: "100%",
          overflow: "visible",
          // Пока ведут неделю -- касания наши; в остальное время по вертикали
          // листает браузер. На экране мышь и так не листает.
          touchAction: phone ? (тащим ? "none" : "pan-y") : "none",
        }}
        onPointerDown={(e) => {
          if (!вПоле(e.clientY)) return;
          начало.current = { x: e.clientX, y: e.clientY };
          if (phone) {
            // Палец на кружке -- ведём неделю; мимо -- отдаём жест странице
            // и решим на отпускании, было ли это касанием.
            if (!наКружке(e.clientX, e.clientY)) return;
            вести(true);
            (e.target as Element).setPointerCapture?.(e.pointerId);
            setHovering(true);
            return;
          }
          (e.target as Element).setPointerCapture?.(e.pointerId);
          setHovering(true);
          pick(e.clientX, e.clientY);
        }}
        /**
         * НЕДЕЛЯ ВЕДЁТСЯ ТОЛЬКО ЗАЖАТОЙ КНОПКОЙ. Прежде точка бежала за
         * курсором сама, и отвести взгляд от графика было нельзя: любое
         * движение мыши по странице меняло выбранную неделю. Теперь нажал --
         * ведёшь, отпустил -- неделя замерла и стоит, пока не нажмёшь снова.
         */
        onPointerMove={(e) => {
          if (phone) {
            if (тащимRef.current && вПоле(e.clientY)) pick(e.clientX, e.clientY);
            return;
          }
          if (e.buttons > 0 && вПоле(e.clientY)) {
            setHovering(true);
            pick(e.clientX, e.clientY);
          }
        }}
        onPointerLeave={() => setHovering(false)}
        onPointerCancel={() => {
          вести(false);
          начало.current = null;
        }}
        onPointerUp={(e) => {
          setHovering(false);
          // Захват отпускаем сами: иначе он держится на элементе, который
          // следующая перерисовка может убрать, и события ушли бы в никуда.
          const t = e.target as Element;
          if (t.hasPointerCapture?.(e.pointerId)) t.releasePointerCapture(e.pointerId);
          if (phone) {
            const н = начало.current;
            начало.current = null;
            if (тащимRef.current) {
              вести(false);
              return;
            }
            // Короткое касание -- выбор недели. Порог в 8 пикселей отделяет
            // касание от начала прокрутки: листание пальцем неделю не двигает.
            if (н && Math.hypot(e.clientX - н.x, e.clientY - н.y) < 8 && вПоле(e.clientY))
              pick(e.clientX, e.clientY);
          }
        }}
      >
        <defs>
          {/* Заливка под кривой -- ТОЖЕ свечение, и в простом виде она
              бледнеет впятеро. Без этого «простой вид» не выглядел простым:
              размытие с линии снималось, а светлая дымка под ней оставалась. */}
          <linearGradient id="areaG" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stopColor={CURVE} stopOpacity={простой ? "0.08" : "0.4"} />
            <stop offset="60%" stopColor={CURVE} stopOpacity={простой ? "0.02" : "0.11"} />
            <stop offset="100%" stopColor={CURVE} stopOpacity="0" />
          </linearGradient>
          <filter id="glow" x="-30%" y="-60%" width="160%" height="260%">
            <feGaussianBlur stdDeviation="5" result="b" />
            <feMerge>
              <feMergeNode in="b" />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>
        </defs>

        {TICKS.map((v) => (
          <g key={v}>
            <line x1={PAD.l} x2={W - PAD.r} y1={y(v)} y2={y(v)} stroke="var(--line)" strokeDasharray="3 7" />
            <text x={PAD.l - 4} y={y(v) + 3} fontSize={phone ? 12 : 16} textAnchor="end" fill="var(--ink-3)" className="mono">
              {v}
            </text>
          </g>
        ))}

        {годы.точки.map((yr, i) => {
          const крайний = i === 0 || i === годы.точки.length - 1;
          const текст = крайний ? String(yr.year) : "’" + String(yr.year).slice(2);
          // Первая подпись прижата к левому краю полотна, последняя к правому:
          // так «2019» не наезжает на «’20», а «2026» не вылезает за холст.
          const ширТ = текст.length * годы.кегль * ШИР_ЗНАКА;
          const x =
            i === 0 ? 0 : i === годы.точки.length - 1 ? Math.min(yr.x + 4, W - ширТ) : yr.x + 4;
          return (
            <g key={yr.year}>
              <line x1={yr.x} x2={yr.x} y1={PAD.t - 12} y2={H - PAD.b} stroke="var(--line)" opacity="0.5" />
              <text x={x} y={H - PAD.b + годы.кегль + 4} fontSize={годы.кегль} fill="var(--ink-3)" className="mono">
                {текст}
              </text>
            </g>
          );
        })}

        {/* Рамки эпохи здесь больше нет. Затенение и черта на 2020 годе
            объясняли устройство прибора (до 2020-го он короче) там, где
            читатель смотрит на кривую, и делили картинку надвое без пользы
            для него. Само правило никуда не делось: место недели считается
            внутри своей эпохи, и это написано словами под числом. */}

        {/* СЕРОЕ ПОЛЕ И ПОДПИСЬ «ПРОГНОЗ ВСЛЕПУЮ» УБРАНЫ. Они делили картинку
            надвое и требовали от читателя держать в голове устройство
            проверки, чтобы понять, на что он смотрит. То же самое сказано
            словами в разделе «как это измерено»: сколько лет прибор
            настраивался и на скольких проверялся. Кривая при этом одна и та
            же на всём ряду -- делить её чертой значило показывать не ряд, а
            наш способ его проверять. */}

        {/* ЛЕНТА РАСХОЖДЕНИЯ -- ТОЛЬКО ПРИ ДВУХ КРИВЫХ. Она показывает
            промежуток МЕЖДУ прибором и опросом, и без кривой прибора её
            верхний край упирается в линию, которой на картинке нет. */}
        {showFom && индекс &&
          gaps.map((g, i) => (
            <path key={i} d={g.d} fill={g.up ? "var(--cool)" : "var(--violet)"} opacity="0.5" />
          ))}

        {индекс && <path d={area} fill="url(#areaG)" />}
        {индекс && <path
          d={line}
          fill="none"
          stroke={CURVE}
          strokeWidth="2.3"
          strokeLinecap="round"
          filter={простой ? undefined : "url(#glow)"}
          className="draw"
          style={{ transition: "stroke 0.35s ease" }}
        />}

        {/* ДЛИТЕЛЬНОСТЬ СОБЫТИЙ -- цветом самой линии. Кусок лежит ровно на
            серебряной кривой (те же изгибы, те же соседи) и чуть толще её,
            чтобы серебро не проступало по краям. Цвет -- показание пиковой
            недели, тот же, что у метки и у точки. Выбранное событие ярче
            прочих. Без анимации отрисовки: она у серебряной линии одна на
            всю кривую, и куски бежали бы наперегонки с ней. */}
        {индекс && полосы.map((п) => (
          <path
            key={"п" + п.i}
            d={п.d}
            fill="none"
            stroke={п.цвет}
            strokeWidth={sel === п.i ? 3.4 : 2.9}
            strokeLinecap="round"
            strokeLinejoin="round"
            opacity={sel === п.i ? 1 : 0.85}
            /* Всегда со свечением: цвет события -- это показание, а не
               оформление, и гасить его переключателем нельзя. */
            filter="url(#glow)"
          />
        ))}

        {showFom && <path d={fomLine} fill="none" stroke="var(--poll)" strokeWidth="1.7" opacity="0.95" />}

        {/* МЕТКИ СОБЫТИЙ. Подпись стоит в общем ряду, а к своей неделе идёт
            выноска: вниз от подписи, наклон, и снова вниз к точке. Подпись,
            выноска и точка -- одно кликабельное целое. stopPropagation
            обязателен: без него клик уходит в полотно, которое выбирает неделю
            по координате мыши, и попадание в край подписи выбирало бы совсем
            другую неделю. */}
        {/* ВЫНОСКИ ОТДЕЛЬНЫМ СЛОЕМ, И ОН НИЖЕ РАМОК. Рисуя каждую метку
            целиком, мы клали выноску соседа под следующую рамку -- на телефоне,
            где рамки стоят в три-четыре ряда, палочки пропадали за ними.
            Теперь сперва все линии, потом все рамки. */}
        {!phone &&
          markers.map((m) => {
            const низ = m.ly + 13;
            const плечо = Math.min(low(m.y) - 14, низ + 26);
            const on = sel === m.i;
            return (
              <polyline
                key={"в" + m.i}
                points={`${m.lx},${низ} ${m.lx},${плечо} ${m.x},${плечо + 12} ${m.x},${m.y - 6}`}
                fill="none"
                stroke="var(--accent-2)"
                strokeWidth={on ? 1.5 : 1}
                opacity={on ? 0.9 : 0.32}
              />
            );
          })}

        {markers.map((m) => {
          const on = sel === m.i;
          return (
            <g
              key={m.i}
              style={{ cursor: "pointer" }}
              onPointerDown={(e) => {
                e.stopPropagation();
                onSel(m.i);
              }}
            >
              {/* Рамка с названием -- только на экране. На телефоне названия
                  стоят полосой над графиком, а здесь остаётся точка на кривой:
                  она и показывает, где событие лежит. */}
              {!phone && <>
              <rect
                x={m.lx - m.wid / 2}
                y={m.ly - 13}
                width={m.wid}
                height={26}
                rx="13"
                fill={on ? moodColor(data[m.i].idx, 6) : "var(--bg-2)"}
                stroke={moodColor(data[m.i].idx, 6, on ? 1 : 0.55)}
                strokeWidth={on ? 1.6 : 1.2}
              />
              <text
                x={m.lx}
                y={m.ly + 5}
                fontSize={m.кегль}
                textAnchor="middle"
                fill={on ? "var(--bg)" : "var(--ink)"}
                style={{ pointerEvents: "none" }}
              >
                {m.text}
              </text>
              </>}
              <circle
                cx={m.x}
                cy={m.y}
                r={on ? 5 : 3.2}
                fill="var(--bg)"
                stroke={moodColor(data[m.i].idx, 6)}
                strokeWidth="1.8"
              />
            </g>
          );
        })}

        <g>
          <line x1={cx} x2={cx} y1={PAD.t - 14} y2={H - PAD.b} stroke="var(--ink)" opacity="0.35" />
          <circle cx={cx} cy={cy} r="6.5" fill="var(--bg)" stroke={CURVE} strokeWidth="2.6" style={{ transition: "stroke 0.35s ease" }} />
          <circle cx={cx} cy={cy} r="12" fill={CURVE} opacity={hovering ? 0.2 : 0.1} style={{ transition: "fill 0.35s ease" }} />
        </g>

        {/* Таблички на телефоне нет: она повторяет то, что и так стоит прямо
            над графиком крупным числом -- неделю и показание, -- а места
            стоила бы столько же, сколько ряд подписей. */}
        {!phone && hovering && (
          /* ШИРИНА 300, А НЕ 250. У недели без опроса во второй строке стоит
             «опроса ФОМа не было» -- девятнадцать знаков, и они не умещались:
             строка начинается на 74 и уходила за правый край рамки. */
          <g transform={`translate(${Math.max(PAD.l, Math.min(flip ? cx - 312 : cx + 14, W - PAD.r - 300))}, ${boxY})`}>
            <rect width="300" height={boxH} rx="12" fill="var(--bg-2)" stroke="var(--line-strong)" opacity="0.98" />
            <text x="14" y="18" fontSize="16" fill="var(--ink-3)" className="mono">
              {fmtWeek(cur.date, lang)}
            </text>
            <text x="14" y="37" fontSize="19" fontWeight="700" fill={moodColor(cur.idx, 8)} className="mono">
              {cur.idx.toFixed(1)}
            </text>
            <text x="74" y="37" fontSize="16" fill="var(--ink-2)" className="mono">
              {cur.fom != null ? `${lang === "ru" ? "опрос" : "poll"} ${cur.fom.toFixed(0)}` : T.fomNone[lang]}
            </text>
          </g>
        )}
      </svg>
    </div>
  );
}
