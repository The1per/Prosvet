import { anxiousOfTen, moodColor, moodT } from "../mood";
import { FLOOR_FOM, PEAK_FOM } from "../data/series";
import type { Lang } from "../i18n";

/**
 * Десять силуэтов, заливаемых СБОКУ, слева направо.
 *
 * Индекс приведён к шкале опроса -- доле тех, у кого настроение вокруг
 * тревожное. Поэтому idx/10 читается прямо: столько человек из десяти.
 * Дробная часть заливает последнего наполовину, а не округляется: округление
 * прибавило бы точности, которой у прибора нет.
 *
 * НЕЗАЛИТЫЕ ВИДНЫ ВСЕГДА. Если их не рисовать, десятка выглядит как пятёрка и
 * пропадает сама мысль «из десяти».
 *
 * ПОЛ. Скобка внизу отмечает, сколько человек называют настроение вокруг
 * тревожным ДАЖЕ в самую спокойную неделю за всё время опроса. Это не
 * оформление, а измеренное свойство опроса: ниже 3,2 из 10 страна не
 * опускалась ни разу. Скобка кончается ровно на 3,2, а не «около трёх».
 *
 * ДРОЖЬ начинается с 70 -- это потолок всего, что опрос когда-либо показывал.
 * Ниже 45 -- ровное дыхание. Между ними покой.
 *
 * СТРОЙ И ПОДПИСЬ РИСУЮТСЯ ПОРОЗНЬ (part). Иначе подпись из двух строк тянет
 * блок вверх, и строй перестаёт стоять вровень с цифрой индекса. В сетке
 * первого экрана строй занимает верхнюю строку -- ту же, где цифра, -- а
 * подпись нижнюю, ту же, где дата под цифрой.
 */

const BODY =
  "M11 3.6a2.6 2.6 0 1 1 0 5.2 2.6 2.6 0 0 1 0-5.2Zm0 6.2c3.1 0 5.2 1.7 5.6 4.4l.7 5.1c.1.9-.5 1.6-1.4 1.6h-1.5l-.5 6.3c-.1.9-.8 1.5-1.6 1.5h-2.6c-.9 0-1.6-.6-1.6-1.5L7.6 20.9H6.1c-.9 0-1.5-.7-1.4-1.6l.7-5.1c.4-2.7 2.5-4.4 5.6-4.4Z";

// 25/5, а не 27/6: строй стоит в одном ряду с числами и управлением, и
// каждый лишний пиксель его ширины -- это пиксель, из-за которого ряд
// рассыпается на две строки. Разницу в два пикселя на фигуру глаз не ловит.
const W = 20;   // было 24: строй ужат, чтобы подписи рядом влезли в две строки
const GAP = 3;
export const PEOPLE_WIDTH = 10 * W + 9 * GAP;
// Телефон: строй ужат так, чтобы десять фигур влезли в 390 пикселей вместе с
// полями карточки, и не забирали высоту у графика.
const W_ТЕЛ = 20;
const GAP_ТЕЛ = 4;

type Props = {
  idx: number;
  lang: Lang;
  /** Значение ползунка опроса, пока посетитель его ведёт: люди отзываются. */
  preview?: number | null;
  part: "строй" | "подпись";
  /** Телефонный вид: фигуры мельче, подписи мельче. */
  phone?: boolean;
  /**
   * Слово уровня («штиль», «напряжение»…). Стоит здесь, а не у числа: у числа
   * оно меняло ширину блока и двигало весь верхний ряд, а тут блок постоянной
   * ширины и подпись просто переносится.
   */
  level?: string;
};

export default function People({ idx, lang, preview = null, part, phone = false, level }: Props) {
  const ш = phone ? W_ТЕЛ : W;
  const зазор = phone ? GAP_ТЕЛ : GAP;
  const ширина = 10 * ш + 9 * зазор;
  const live = preview ?? idx;
  const v = anxiousOfTen(live);
  const color = moodColor(live, 4);
  const t01 = Math.max(0, Math.min(1, (live - 70) / 30));
  const shiver = preview !== null && live >= 70;
  const calm = preview !== null && live < 45;

  // ПОЛ И ПОТОЛОК ОПРОСА -- измеренные, не назначенные: за одиннадцать лет
  // опрос не опускался ниже 32 % и не поднимался выше 70 %.
  const floor = FLOOR_FOM / 10;
  const peak = PEAK_FOM / 10;
  // Дробной позиции больше не нужно: границы стоят В ПРОМЕЖУТКАХ между
  // фигурами, а не в дробных долях фигуры.
  /** Середина промежутка после k-й фигуры: граница между людьми. */
  const вПромежуток = (v: number) => {
    const k = Math.max(1, Math.min(9, Math.round(v)));
    return k * (ш + зазор) - зазор / 2;
  };

  const shown = (Math.round(v * 10) / 10).toFixed(1);
  const ru = lang === "ru";
  // Пока посетитель ведёт ползунок, силуэты показывают ЕГО ответ, и подпись
  // обязана это назвать. Иначе она выдаёт ответ посетителя за показание.
  const label =
    preview !== null
      ? ru
        ? `по-вашему — ${shown.replace(".", ",")} из 10`
        : `by your reading — ${shown} in 10`
      : ru
        // «Тревожны 5,4 из 10» -- короче всего прежнего и читается сразу.
        // Слово уровня стоит отдельной строкой над этим, и вместе выходит
        // «Напряжение / Тревожны 5,4 из 10».
        ? `Тревожны ${shown.replace(".", ",")} из 10`
        : `${shown} in 10 are anxious`;
  // КОРОЧЕ ПРЕЖНЕГО. Было «...даже в самую спокойную неделю за всё время
  // опроса»: строка занимала три строки под фигурами и читалась дольше, чем
  // стоит подпись. «За всё время опроса» и так следует из «самой спокойной».
  // В ОДНУ СТРОКУ. «Даже» и «за всё время опроса» убраны: строка занимала под
  // фигурами три строки, а сказано в ней одно -- столько тревожных бывает и в
  // самую спокойную неделю.
  // БЕЗ ЧИСЛА. Величину пола показывает пунктирная скобка под строем -- она
  // и есть число, нарисованное. Повторять его цифрой значило говорить дважды
  // об одном, а строка от этого росла втрое.

  if (part === "подпись") {
    // Подпись НЕ ШИРЕ САМОГО СТРОЯ: со свободными 110 пикселями блок выходил
    // 434 в ширину -- самый широкий в ряду, и из-за него показатели не
    // складывались в одну строку. Строк в подписи стало больше, зато ряд один.
    return (
      <div className="space-y-1" style={{ maxWidth: phone ? "100%" : ширина }}>
        {/* Слово уровня стоит В ОДНОЙ СТРОКЕ с подписью, но занимает
            ПОСТОЯННОЕ МЕСТО. Отдельной строкой оно добавляло блоку целую
            строку, а без заданной ширины -- перекладывало подпись на другое
            число строк, потому что «штиль» и «напряжение» разной длины.
            Ширина взята под самое длинное слово шкалы. */}
        {/* На экране главная строка стоит СПРАВА ОТ ФИГУР (см. part="строй"),
            и здесь остаётся только пол опроса -- иначе блок занимал на строку
            больше и весь верхний ряд уезжал вниз. На телефоне места вбок нет,
            и она по-прежнему тут. */}
        {/* НА ТЕЛЕФОНЕ ВСЁ В ОДНУ СТРОКУ, и она не переносится.
            Кегль привязан к ширине экрана: строка занимает 49 знаков, а знак
            моноширинного здесь -- 0.61 кегля, поэтому 3 vw укладывают её в
            карточку и на 320, и на 430. Слово уровня сидит в коробке
            постоянной ширины в 6.1 знака -- иначе «фон» и «напряжение» разной
            длины двигали бы подпись при каждом переходе на другую неделю. */}
        {phone && (
          <div
            className="mono whitespace-nowrap"
            style={{ color: "var(--ink-2)", fontSize: "clamp(15px, 3.6vw, 17px)" }}
          >
            {/* СЛОВА УРОВНЯ НА ТЕЛЕФОНЕ НЕТ. Подпись теперь начинается словом
                «Тревожны», и «Напряжение Тревожны 5,4 из 10» читалось как
                сбой. Уровень и без того сказан цветом фигур. На экране места
                хватает, и там он стоит отдельной строкой над подписью. */}
            {label}
          </div>
        )}
        {/* Строки про пол опроса здесь больше нет: пределы показаны
            отсечками под строем, в part="строй". */}
      </div>
    );
  }

  // items-start: главная строка начинается на одной высоте с фигурами. По
  // центру она садилась ниже них и переставала читаться как подпись к строю.
  return (
    // ПОЛ ОПРОСА -- ВО ВСЮ ШИРИНУ БЛОКА, под фигурами И подписью. Он стоял под
    // одними фигурами, и его собственная ширина тянула левый столбец: в кегле
    // раздела строка не влезала под фигуры и распирала весь ряд. Растянутый на
    // весь блок, он укладывается в одну строку и ничего не двигает.
    <div className={phone ? "" : ""}>
    <div className={phone ? "" : "flex items-start gap-5"}>
    <div>
    <div className="relative inline-block" style={{ width: ширина }}>
      <div className="flex items-end" style={{ gap: зазор }} role="img" aria-label={label}>
        {Array.from({ length: 10 }, (_, i) => {
          const fill = Math.max(0, Math.min(1, v - i));
          const id = `pm${i}`;
          return (
            <svg
              key={i}
              viewBox="0 0 22 32"
              className={`shrink-0 ${shiver ? "shiver" : calm ? "breathe" : ""}`}
              style={{
                width: ш,
                height: phone ? 30 : 40,
                ["--sx" as string]: `${(0.3 + t01 * 1.1).toFixed(2)}px`,
                ["--sr" as string]: `${(t01 * 1.6).toFixed(2)}deg`,
                ["--sd" as string]: `${(0.42 - t01 * 0.22).toFixed(2)}s`,
                animationDelay: `${(i * 37) % 190}ms`,
                filter:
                  fill > 0
                    ? `drop-shadow(0 0 ${(3 + 6 * moodT(live)).toFixed(1)}px ${moodColor(live, 0, 0.45)})`
                    : "none",
              }}
              aria-hidden
            >
              <defs>
                <linearGradient id={id} x1="0" y1="0" x2="1" y2="0">
                  <stop offset="0%" stopColor={color} />
                  <stop offset={`${fill * 100}%`} stopColor={color} />
                  <stop offset={`${fill * 100}%`} stopColor="transparent" />
                  <stop offset="100%" stopColor="transparent" />
                </linearGradient>
              </defs>
              <path d={BODY} fill="var(--card-2)" stroke="var(--line-strong)" strokeWidth="0.8" />
              <path d={BODY} fill={`url(#${id})`} style={{ transition: "fill 0.8s ease" }} />
            </svg>
          );
        })}
      </div>

      {/* ПРЕДЕЛЫ ОПРОСА -- ДВЕ ОТСЕЧКИ ПОД СТРОЕМ вместо подписи словами.
          Прежде пол показывался и скобкой, и строкой «минимум за всё время»:
          одно и то же говорилось дважды, а строка занимала место. Теперь
          обе границы нарисованы: докуда опрос опускался и докуда поднимался
          за одиннадцать лет. Читателю это говорит, широка ли шкала, на
          которой стоит сегодняшнее число. */}
      {/* Подписи БЕЛЫЕ и в общем кегле страницы. Одиннадцать пикселей серым
          -- это не подпись, а её след; такого кегля на странице нет нигде и
          быть не должно. Отсечки подняты вплотную к строю: они про него. */}
      {/* ОТСЕЧКИ СТОЯТ В ПРОМЕЖУТКАХ МЕЖДУ ФИГУРАМИ, а не поперёк них:
          граница проходит между людьми, а не через человека. Черта короткая и
          начинается сразу под строем; подпись под чертой, но не вплотную. */}
      {/* ОТСЕЧКА УШЛА В САМ СТРОЙ. Прежде она стояла под ним и подпись висела
          в шести пикселях ниже фигур -- на телефоне это отодвигало всё, что
          под строем. Теперь черта занимает последние пять пикселей ПРОМЕЖУТКА
          МЕЖДУ ФИГУРАМИ, где всё равно пусто, и кончается ровно на их низе, а
          подпись садится ВРОВЕНЬ С НИЗОМ ФИГУР. Выше поднять уже нельзя: в
          силуэте под ногами есть три пикселя пустоты, туда черта и уходит, а
          межстрочный просвет у подписи снят (lineHeight 1) -- он и держал те
          пять пикселей, из-за которых подпись висела в стороне от строя. */}
      {[["мин.", вПромежуток(floor)], ["макс.", вПромежуток(peak)]].map(([метка, x]) => (
        <div
          key={метка as string}
          className="pointer-events-none absolute bottom-[2px]"
          style={{ left: (x as number) - 0.5, height: 4 }}
          aria-hidden
        >
          <div style={{ width: 1, height: 4, background: "var(--ink)" }} />
          <div
            className="mono absolute top-[5px] -translate-x-1/2 whitespace-nowrap"
            style={{ left: 0, fontSize: phone ? 15 : 19, lineHeight: 1, color: "var(--ink)" }}
          >
            {метка}
          </div>
        </div>
      ))}
    </div>
    {/* ПОЛ ОПРОСА -- ПРЯМО ПОД ФИГУРАМИ и вплотную к ним: он про них, и
        пунктирная скобка под строем показывает ту же величину. Кегль тот же,
        что у строки справа, -- это две подписи одного веса, а не подпись и
        приписка к ней. */}
    </div>

    {/* Главная строка -- вплотную справа от фигур и вровень с ними: она про
        них и есть. Ширина задана, иначе блок растянулся бы на всю свободную
        ширину ряда и вытолкнул из строки числа сравнения. */}
    {/* Кегль 14.5, а не 17. Строка стоит вплотную к строю и к главному числу
        недели, и в прежнем росте читалась вровень с ними -- как второе
        показание, а не как подпись к первому. */}
    {!phone && (
      // Слово уровня СТОИТ В СТРОКУ с подписью, а не отдельной строкой над
      // ней: отдельной строкой вся подпись занимала четыре строки при трёх
      // словах смысла. Коробка шире прежней ровно настолько, чтобы вышло две.
      <div className="mono text-[19px] leading-snug" style={{ color: "var(--ink-2)", width: 210 }}>
        {level && (
          <b className="block font-semibold" style={{ color: "var(--ink)" }}>
            {level[0].toUpperCase() + level.slice(1)}
          </b>
        )}
        {label}
      </div>
    )}
    </div>
    </div>
  );
}
