/**
 * Два полюса ползунка: покой и тревога.
 *
 * Та же фигура человека, что в десяти силуэтах у числа, — чтобы полюса
 * читались как продолжение показания, а не как посторонние значки.
 *
 * ПОКОЙ: три пустые фигуры, ровно в ряд, на одной линии. Пустые — потому что
 * пустой силуэт на этой странице и означает «не тревожно».
 *
 * ТРЕВОГА: та же толпа сбита в кучку и залита цветом, и с 70 начинает
 * дрожать. Фигуры стоят ВПЛОТНУЮ, но НЕ НАЛЕЗАЮТ друг на друга: налезающие
 * читаются как клякса, и тогда пропадает, что это люди.
 *
 * Заливка берётся из токенов этого оформления. Раньше здесь стоял --bg3 из
 * прежней страницы, которого тут нет: спокойные фигуры заливались ничем.
 */

const BODY =
  "M11 3.6a2.6 2.6 0 1 1 0 5.2 2.6 2.6 0 0 1 0-5.2Zm0 6.2c3.1 0 5.2 1.7 5.6 4.4l.7 5.1c.1.9-.5 1.6-1.4 1.6h-1.5l-.5 6.3c-.1.9-.8 1.5-1.6 1.5h-2.6c-.9 0-1.6-.6-1.6-1.5L7.6 20.9H6.1c-.9 0-1.5-.7-1.4-1.6l.7-5.1c.4-2.7 2.5-4.4 5.6-4.4Z";

// Фигура занимает по ширине примерно 14 единиц (x от 4.4 до 17.6).
// Шаг 15 -- вплотную, но без наложения. Шаг 14 и меньше уже налезает.
const STEP = 15;

const CALM = [
  { x: 0, y: 6, r: 0 },
  { x: STEP, y: 6, r: 0 },
  { x: STEP * 2, y: 6, r: 0 },
];

// Кучка: тот же шаг, но фигуры сбиты по высоте и повёрнуты кто куда.
const CROWD = [
  { x: 0, y: 9, r: -9 },
  { x: STEP, y: 3, r: 5 },
  { x: STEP * 2, y: 8, r: -4 },
  { x: STEP * 3, y: 2, r: 8 },
];

type Props = { kind: "calm" | "chaos"; color: string; title: string; live?: boolean };

export default function Poles({ kind, color, title, live = false }: Props) {
  const calm = kind === "calm";
  const rows = calm ? CALM : CROWD;
  const w = (rows.length - 1) * STEP + 22;

  return (
    <svg
      viewBox={`0 0 ${w} 44`}
      className={calm ? "h-[42px] w-[62px] shrink-0" : "h-[42px] w-[80px] shrink-0"}
      role="img"
      aria-label={title}
    >
      <title>{title}</title>
      {calm && <line x1="1" y1="41" x2={w - 1} y2="41" stroke="var(--line-strong)" strokeWidth="1" />}
      {/* ДВА ВЛОЖЕННЫХ g, И ЭТО ОБЯЗАТЕЛЬНО. Свойство transform в CSS-анимации
          перебивает одноимённый SVG-атрибут: поставь их на один элемент -- и
          все фигуры на время дрожи схлопываются в одну точку. Внешний g
          расставляет, внутренний дрожит. */}
      {rows.map((p, i) => (
        <g key={i} transform={`translate(${p.x} ${p.y}) rotate(${p.r} 11 20)`}>
          <g
            className={live ? (calm ? "breathe" : "shiver") : ""}
            style={{
              ["--sx" as string]: "1.1px",
              ["--sr" as string]: "1.5deg",
              ["--sd" as string]: "0.24s",
              animationDelay: `${i * 61}ms`,
            }}
          >
            <path
              d={BODY}
              fill={calm ? "none" : color}
              stroke={calm ? "var(--ink-2)" : "var(--bg)"}
              strokeWidth={calm ? 1.1 : 0.7}
              opacity={calm ? 0.8 : 1}
            />
          </g>
        </g>
      ))}
    </svg>
  );
}
