import { FLOOR_FOM, PEAK_FOM } from "./data/series";

/**
 * Цвет настроения и «сколько человек из десяти».
 *
 * ШКАЛА. Индекс приведён к шкале опроса: это доля тех, кто говорит, что
 * настроение вокруг тревожное. Поэтому перевод в людей прямой -- idx/10 из
 * десяти, без всякой отдельной модели.
 *
 * Отсюда же и растяжка цвета. За одиннадцать лет опрос ходил в пределах
 * 32…70 %, и ни разу не был ни у 0, ни у 100. Раскрась мы 0…100 -- весь ряд
 * оказался бы в одном оттенке и цвет перестал бы что-либо значить. Поэтому
 * ступени цвета привязаны к ИЗМЕРЕННЫМ полу и потолку, а не к круглым числам.
 *
 * Цвет нигде не выбирается вручную: право менять его -- право врать о
 * показании.
 */

const LO = FLOOR_FOM; // 32 -- самая спокойная неделя за одиннадцать лет
const HI = PEAK_FOM; // 70 -- самая тревожная

/** Спокойный бирюзовый → выжидающий янтарь → тревожный красный. */
const STOPS: { t: number; h: number; s: number; l: number }[] = [
  { t: 0.0, h: 168, s: 52, l: 46 },
  { t: 0.36, h: 55, s: 74, l: 50 },
  { t: 0.68, h: 28, s: 84, l: 52 },
  { t: 1.0, h: 6, s: 80, l: 51 },
];

const clamp = (v: number, a: number, b: number) => Math.max(a, Math.min(b, v));

/**
 * На светлом фоне те же оттенки читаются хуже: янтарный на кремовом почти
 * пропадает. Поэтому в светлой теме вся шкала темнеет на одну и ту же
 * величину -- цвет по-прежнему означает ровно величину тревоги, просто взят
 * на фоне, на котором его видно.
 */
let СВЕТЛАЯ = false;
export function setMoodTheme(t: "dark" | "light") {
  СВЕТЛАЯ = t === "light";
}

/** 0 в самую спокойную неделю ряда, 1 в самую тревожную. */
export function moodT(idx: number): number {
  return clamp((idx - LO) / (HI - LO), 0, 1);
}

function hsl(idx: number) {
  const t = moodT(idx);
  let i = 0;
  while (i < STOPS.length - 2 && t > STOPS[i + 1].t) i++;
  const a = STOPS[i];
  const b = STOPS[i + 1];
  const k = (t - a.t) / (b.t - a.t || 1);
  return {
    h: a.h + (b.h - a.h) * k,
    s: a.s + (b.s - a.s) * k,
    l: a.l + (b.l - a.l) * k + (СВЕТЛАЯ ? -16 : 0),
  };
}

/** Основной цвет настроения. lOff светлит, a задаёт непрозрачность. */
export function moodColor(idx: number, lOff = 0, a = 1): string {
  const { h, s, l } = hsl(idx);
  return `hsl(${h.toFixed(1)} ${s.toFixed(1)}% ${clamp(l + lOff, 8, 92).toFixed(1)}% / ${a})`;
}

/** Три оттенка одного семейства для свечения за числом. */
export function moodGlow(idx: number) {
  const { h, s, l } = hsl(idx);
  const hue = (dh: number, ds: number, dl: number, al: number) =>
    `hsl(${(((h + dh) % 360) + 360) % 360} ${clamp(s + ds, 0, 100).toFixed(1)}% ${clamp(l + dl, 8, 92).toFixed(1)}% / ${al})`;
  const t = moodT(idx);
  // Свет сидит прямо за цифрой, а карточка полупрозрачна: возьми прежнюю силу
  // -- и он выест подписи вокруг числа. Здесь он заметен, но читается как
  // подсветка, а не как заливка.
  return {
    core: hue(0, 4, 4, 0.2 + 0.14 * t),
    mid: hue(14, -10, -2, 0.1 + 0.08 * t),
    far: hue(-22, -16, -8, 0.06 + 0.05 * t),
  };
}

/** Сколько человек из десяти, с одним знаком после запятой. */
export function anxiousOfTen(idx: number): number {
  return clamp(idx / 10, 0, 10);
}

/**
 * Название уровня. Границы -- доли измеренного размаха, а не круглые числа:
 * делить 0…100 на пятёрки значило бы, что «штиля» и «паники» не бывает
 * никогда, потому что опрос туда не заходит.
 */
export function levelIndex(idx: number): number {
  return clamp(Math.floor(moodT(idx) * 5), 0, 4);
}
