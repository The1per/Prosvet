/**
 * Масштаб страницы под ширину экрана.
 *
 * ЗАЧЕМ ИМЕННО ТАК. Раскладка рассчитана на широкий экран: число, строй людей
 * и числа сравнения стоят в один ряд, и это осмысленно -- их сравнивают
 * глазом. На ноутбуке с узким экраном она не влезала. Ломать её на этих
 * ширинах не нужно: достаточно показать то же самое МЕЛЬЧЕ.
 *
 * Поэтому здесь `zoom` -- он масштабирует и размеры, и раскладку целиком,
 * в отличие от `transform: scale`, который оставляет прежние размеры места и
 * ломает прокрутку.
 *
 * НИЖНЯЯ ГРАНИЦА. Уменьшать без предела нельзя: на телефоне 1400 пикселей,
 * сжатые до 375, дают нечитаемый текст. Ниже ПРЕДЕЛА масштаб перестаёт
 * падать, и дальше раскладка переносится сама -- ряды в ней собраны
 * переносимыми блоками именно на этот случай.
 */

// 1600, а не 1440: на 1280-1440 включаются две колонки (график и опрос по 400),
// и левой карточке остаётся меньше, чем нужно верхнему ряду. Опорная взята
// такой, чтобы на этих ширинах ряд оставался одной строкой.
const ОПОРНАЯ = 1600;
const ПРЕДЕЛ = 0.62; // мельче не делаем: дальше нечитаемо

/**
 * ГРАНИЦА ТЕЛЕФОНА. Уже неё сжимать бессмысленно и вредно: страница, рассчитанная
 * на 1600, ужатая до 390, давала кегль 10 пикселей -- прочесть нельзя. Ниже этой
 * ширины масштаб не трогается вовсе, а раскладка своя: один столбец, свой
 * порядок блоков, свой график. См. useТелефон в hooks.ts -- граница одна и та же.
 */
// 768, а не 700: ровно здесь у раскладки порог md, на котором столбцы
// расходятся надвое. При 700 оставалась полоса 700-767, где раскладка уже
// однослойная, а вид ещё экранный -- и опрос в ней не показывался вовсе.
export const ТЕЛЕФОН = 768;

/**
 * ВЫСОТА ГРАФИКА СЧИТАЕТСЯ ЗДЕСЬ, А НЕ В CSS.
 *
 * График должен помещаться на экран без прокрутки. В CSS это не выражается:
 * страница масштабируется через zoom, а единица vh мерит экран ДО масштаба --
 * значит на суженной странице calc(100vh - ...) даёт не тот остаток, и график
 * то не влезает, то не добирает высоты.
 *
 * Здесь известно и то и другое: верх графика в раскладке стоит на постоянном
 * месте (ВЕРХ), а экран в единицах раскладки -- это высота окна, делённая на
 * масштаб. Остаток и есть высота графика.
 */
/**
 * 12 сентября 2026, по просьбе хозяина: график ВЫШЕ И ЧУТЬ НИЖЕ РОСТОМ.
 *
 * ВЕРХ 305 -> 293: блок слов недели поднят на двенадцать пикселей (-mt-6 ->
 * -mt-9 в App.tsx), значит и холст начинается на двенадцать выше. Эти два
 * числа обязаны меняться вместе: ВЕРХ здесь -- не настройка, а измеренное
 * место холста в раскладке, и разойдясь с ней, он либо оставляет под графиком
 * пустую полосу, либо загоняет его низ за край экрана.
 *
 * ПОДВАЛ 22 -> 70: сам график сжат по высоте на тридцать шесть пикселей.
 * Подвал -- это то, что остаётся под ним, и он же ручка роста: высота графика
 * считается как весь остаток экрана, поэтому уменьшить её можно только отдав
 * место низу. Вместе получается: верх графика на 12 выше, низ на 48 выше.
 */
const ВЕРХ = 293; // где начинается холст, в единицах раскладки -- измерено
const ПОДВАЛ = 70; // остаток под графиком; он же задаёт его рост
const ГРАФИК_МИН = 300;
// 740 -> 700 тем же решением: на высоком экране остаток велик и высоту задаёт
// именно этот потолок, а не подвал. Оставь его прежним -- и на большом мониторе
// график не сжался бы ни на пиксель, хотя на ноутбуке сжался бы.
const ГРАФИК_МАКС = 700;
// Телефон: график занимает больше половины экрана. Меньше -- кривая
// превращается в полоску, больше -- под ним не остаётся ничего, за чем листать.
// 0.66 экрана оказалось слишком: холст выходил почти квадратным, кривая в
// нём вытягивалась вверх и читалась как пережатая. Ширину не трогаем -- она
// и так во весь экран, -- а высоту берём меньше: на 390x844 это 388 пикселей
// при ширине 348, то есть пропорции близки к альбомным, как на экране.
const ТЕЛ_ДОЛЯ = 0.38;
const ТЕЛ_МИН = 250;
const ТЕЛ_МАКС = 380;

export function следитьЗаМасштабом() {
  const применить = () => {
    const w = document.documentElement.clientWidth;
    const h = document.documentElement.clientHeight;
    const телефон = w < ТЕЛЕФОН;
    const м = телефон ? 1 : Math.min(1, Math.max(ПРЕДЕЛ, w / ОПОРНАЯ));
    // zoom в типах TS не описан, хотя есть во всех нынешних браузерах
    (document.documentElement.style as unknown as Record<string, string>).zoom =
      м === 1 ? "" : String(Math.round(м * 1000) / 1000);

    // На телефоне график меряется от ЭКРАНА, а не от остатка страницы: там всё
    // равно листают, и задача не «влезть без прокрутки», а «быть крупным».
    const место = телефон ? h * ТЕЛ_ДОЛЯ : h / м - ВЕРХ - ПОДВАЛ;
    const мин = телефон ? ТЕЛ_МИН : ГРАФИК_МИН;
    const макс = телефон ? ТЕЛ_МАКС : ГРАФИК_МАКС;
    document.documentElement.style.setProperty(
      "--chart-h",
      Math.round(Math.min(макс, Math.max(мин, место))) + "px",
    );
  };
  применить();
  window.addEventListener("resize", применить, { passive: true });
  return () => window.removeEventListener("resize", применить);
}
